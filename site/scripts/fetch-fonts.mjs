// One-shot, reproducible helper (NOT part of the build) that self-hosts the
// Google Fonts woff2 files. It fetches the css2 stylesheets, downloads every
// referenced latin / latin-ext woff2 into public/fonts with deterministic
// names, and writes the consolidated @font-face stylesheet to
// src/styles/fonts.css (bundled; its url('/fonts/*.woff2') references resolve
// to the public files at runtime). No <link> to Google is used at runtime.
//
// Families: DM Sans (400/500/600), DM Mono (400/500), Newsreader (400 + italic).
// Arabic renders via a per-script system stack (DESIGN.md), so no Arabic webfont
// is bundled. Run from the site/ directory: node scripts/fetch-fonts.mjs
import { writeFileSync, createWriteStream, mkdirSync } from 'node:fs'
import { pipeline } from 'node:stream/promises'

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'

// css2 requests. The modern UA makes Google return woff2 sources.
const sources = [
  {
    family: 'DM Sans',
    slug: 'dmsans',
    url: 'https://fonts.googleapis.com/css2?family=DM+Sans:wght@400;500;600&display=swap',
  },
  {
    family: 'DM Mono',
    slug: 'dmmono',
    url: 'https://fonts.googleapis.com/css2?family=DM+Mono:wght@400;500&display=swap',
  },
  {
    family: 'Newsreader',
    slug: 'newsreader',
    url: 'https://fonts.googleapis.com/css2?family=Newsreader:ital,wght@0,400;1,400&display=swap',
  },
]

const publicFontsDir = new URL('../public/fonts/', import.meta.url)
const stylesheetPath = new URL('../src/styles/fonts.css', import.meta.url)
mkdirSync(publicFontsDir, { recursive: true })

// Parse @font-face blocks, preserving the preceding subset comment.
function parseFaces(cssText) {
  const faces = []
  const re = /\/\*\s*([^*]+?)\s*\*\/\s*@font-face\s*{([^}]+)}/g
  let m
  while ((m = re.exec(cssText))) {
    const subset = m[1].trim()
    const body = m[2]
    const weight = (body.match(/font-weight:\s*([^;]+);/) || [])[1]?.trim()
    const style = (body.match(/font-style:\s*([^;]+);/) || [])[1]?.trim()
    const url = (body.match(/url\(([^)]+)\)/) || [])[1]?.trim()
    const range = (body.match(/unicode-range:\s*([^;]+);/) || [])[1]?.trim()
    faces.push({ subset, weight, style, url, range })
  }
  return faces
}

const out = []
const downloads = new Map() // url -> filename

for (const src of sources) {
  const cssRes = await fetch(src.url, { headers: { 'User-Agent': UA } })
  if (!cssRes.ok) throw new Error(`Failed css ${src.url}: ${cssRes.status}`)
  const cssText = await cssRes.text()
  for (const f of parseFaces(cssText)) {
    // Keep only latin and latin-ext (Danish diacritics live here).
    if (f.subset !== 'latin' && f.subset !== 'latin-ext') continue
    const styleTag = f.style === 'italic' ? 'italic' : 'normal'
    // Google serves DM Sans as a single variable woff2 shared across weights
    // (same URL for 400/500/600 within a subset). Dedupe the physical file by
    // URL, keeping the first name we assigned, so every @font-face src below
    // resolves to a file that is actually downloaded. Without this, later
    // weights would reference woff2 filenames that never get written.
    if (!downloads.has(f.url)) {
      downloads.set(f.url, `${src.slug}-${f.weight}-${styleTag}-${f.subset}.woff2`)
    }
    const name = downloads.get(f.url)
    out.push({ family: src.family, weight: f.weight, style: styleTag, name, range: f.range })
  }
}

// Download every unique woff2 into public/fonts.
for (const [url, name] of downloads) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`Failed ${url}: ${res.status}`)
  await pipeline(res.body, createWriteStream(new URL(name, publicFontsDir)))
  console.log('downloaded', name)
}

// Emit the consolidated stylesheet.
const header = `/* Self-hosted webfonts for Belief Changer.
 * Generated by scripts/fetch-fonts.mjs from the Google Fonts css2 API.
 * No <link> to Google is used at runtime; these woff2 files are served locally
 * from /public/fonts. Families: DM Sans (400/500/600), DM Mono (400/500),
 * Newsreader (400 + italic). Arabic renders via a per-script system stack
 * (see styles/globals.css), so no Arabic webfont is bundled. Every face uses
 * font-display: swap. */\n\n`

const css =
  header +
  out
    .map(
      (f) => `@font-face {
  font-family: '${f.family}';
  font-style: ${f.style};
  font-weight: ${f.weight};
  font-display: swap;
  src: url('/fonts/${f.name}') format('woff2');
  unicode-range: ${f.range};
}`,
    )
    .join('\n\n') +
  '\n'

writeFileSync(stylesheetPath, css)
console.log('\nwrote src/styles/fonts.css with', out.length, 'faces')
